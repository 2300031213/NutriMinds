def lookup_nutrition(food_name: str) -> Optional[Dict[str, Any]]:
    """
    Look up nutrition for a food item by exact key, normalized slug, or alias.
    Returns standard dictionary with nutrition breakdown or None.
    """
    if not food_name:
        return None

    clean_key = food_name.strip().lower()
    
    # Check exact match
    if clean_key in FOOD_NUTRITION_DATABASE:
        return FOOD_NUTRITION_DATABASE[clean_key]
        
    # Check underscore replaced with space
    clean_space = clean_key.replace("_", " ")
    if clean_space in FOOD_ALIASES:
        target = FOOD_ALIASES[clean_space]
        if target in FOOD_NUTRITION_DATABASE:
            return FOOD_NUTRITION_DATABASE[target]

    # Check space replaced with underscore
    clean_slug = clean_key.replace(" ", "_")
    if clean_slug in FOOD_NUTRITION_DATABASE:
        return FOOD_NUTRITION_DATABASE[clean_slug]

    if clean_key in FOOD_ALIASES:
        target = FOOD_ALIASES[clean_key]
        if target in FOOD_NUTRITION_DATABASE:
            return FOOD_NUTRITION_DATABASE[target]

    # Substring search across keys
    for k, data in FOOD_NUTRITION_DATABASE.items():
        if k in clean_slug or clean_slug in k:
            return data

    return None
